// Langue active
let currentLang = 'pt';

function detectLang() {
  const path = window.location.pathname;
  if (path.includes('/fr/') || path.includes('/fr')) return 'fr';
  if (path.includes('/en/') || path.includes('/en')) return 'en';
  return 'pt';
}

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) ||
         (TRANSLATIONS['pt'] && TRANSLATIONS['pt'][key]) || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  const menuToggle = document.getElementById('menu-toggle');
  if (menuToggle) {
    menuToggle.setAttribute('aria-label', t(
      menuToggle.getAttribute('aria-expanded') === 'true' ? 'aria_menu_close' : 'aria_menu_open'
    ));
  }
  // Update html lang attribute
  document.documentElement.lang = currentLang;
  // Update active lang button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
    btn.setAttribute('aria-current', btn.getAttribute('data-lang') === currentLang ? 'true' : 'false');
  });
}

function switchLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('mc_lang', lang);
  applyTranslations();
  // Update URL without reload
  const url = new URL(window.location.href);
  url.searchParams.set('lang', lang);
  history.replaceState({}, '', url.toString());
}

function initLang() {
  const urlParams = new URLSearchParams(window.location.search);
  const stored = localStorage.getItem('mc_lang');
  const urlLang = urlParams.get('lang');
  if (urlLang && TRANSLATIONS[urlLang]) {
    currentLang = urlLang;
  } else if (stored && TRANSLATIONS[stored]) {
    currentLang = stored;
  } else {
    currentLang = 'pt';
  }
  localStorage.setItem('mc_lang', currentLang);
  applyTranslations();
}